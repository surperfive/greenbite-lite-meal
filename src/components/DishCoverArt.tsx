/** 裸图模式下内容**最长边**占容器的百分比。90 是留一点余量、又不至于显得空的值。 */
const BARE_FILL = 90;

/**
 * 把 `dish.bg` 调成"盘子色"：与白色混合 `whiteRatio`，降浊度、不换色相。
 *
 * 为什么需要：`dish.bg` 是早期商品卡的背景色块值（要能托住白色卡片），
 * 直接铺成椭圆盘时，橙 `#FBAE68`、棕 `#C9A375` 这类低明度色会显得脏，
 * 黑字压在边缘也发灰。混 10% 白基本看不出色相变化，但盘面立刻"干净"一档。
 * ⚠️ 比例别超过 0.18：再高就和白色卡片糊成一片，色块失去品类识别作用。
 */
const soften = (hex: string, whiteRatio = 0.1) => {
  const h = hex.replace('#', '').trim();
  if (!/^[0-9a-fA-F]{6}$/.test(h)) return hex; // 兜底：非 6 位 hex 原样返回
  const n = parseInt(h, 16);
  const toHex = (c: number) => c.toString(16).padStart(2, '0');
  const mix = (c: number) => Math.round(c + (255 - c) * whiteRatio);
  return `#${toHex(mix((n >> 16) & 255))}${toHex(mix((n >> 8) & 255))}${toHex(mix(n & 255))}`;
};

/** 没有 `dish.bg` 的兜底盘色（= 旧的统一青柠，保证新增菜不会渲染成透明盘）。 */
const DEFAULT_DISC = '#C7F665';

/**
 * 食物投影（详情页 hero 用）。
 * ⚠️ 必须是 `drop-shadow` 不能是 `box-shadow`：抠图是透明 PNG，
 *    box-shadow 会照着**矩形边框**画一圈，drop-shadow 才跟着 alpha 轮廓走。
 * ⚠️ 两层叠加：内层近距定形（贴地的接触影），外层稍远做氛围。
 *    单层的话要么太硬像贴纸、要么没落地感。
 * ⚠️ **量程必须压在 hero 的 19px 余量里**：食物 185 盒子的内容底在 hero 的
 *    ~201px，hero 底边 220px 且 `overflow-hidden`，阴影越过 220 就被硬切一刀，
 *    杯底下面出现一条平直的灰带（用户原话"阴影被挡住"）。
 *    原参数 `0 5px 8px .20 / 0 14px 26px .16` 向下延伸约 40px，被裁掉一大半。
 * ⚠️ "削弱范围"不等于"同时削弱浓度"：范围砍到 1/4 后浓度若也跟着降，
 *    杯底就完全浮空（试过 .14/.08，放大看几乎没有影）。所以近端那层
 *    反而提到 .30，做一条贴着杯底的窄接触影，远端仍很淡。
 * ⚠️ 实测口径（`scripts/_shadow-col.py`，取杯子中轴单列亮度）：
 *    标准份 201→217 平滑收敛到 255，220 处无跳变 ✓；
 *    大份（素材里多了一把咖啡豆，底部再低 3px）还要靠 ProductDetailPage 里
 *    那组 `origin-bottom -translate-y-[4px]` 补偿，残留 1 个色阶（253→255 收到 254）。
 * ⚠️ 改这里的 y/blur 之前先跑一遍扫描脚本 —— 凭肉眼判断"看起来挺淡"会翻车，
 *    253 和 255 在缩略图里看不出，放大就是一条横线。
 * ⚠️ 点餐页卡片**不要开**：那里食物压在青柠椭圆盘上，投影会让盘面显脏。
 */
export const FOOD_SHADOW =
  'drop-shadow(0 2px 4px rgba(0,0,0,0.30)) drop-shadow(0 4px 5px rgba(0,0,0,0.14))';

/**
 * 食物外轮廓光（详情页 hero 用，第二轮用户原话"给商品加一个微弱的外轮廓光"）。
 * ⚠️ 同为 drop-shadow（跟 alpha 轮廓），但方向相反：`FOOD_SHADOW` 是暗色向下管落地，
 *    这个是白光零偏移管分离 —— 上下分工，叠在一起就是电商商品图经典的
 *    「rim light + drop shadow」处理。
 * ⚠️ 颜色必须是白/暖白：hero 背景是暗调食材微距照片，亮光才可见。
 *    用青柠 `#C7F665` 会和背景里的品牌元素撞色，还会让食物边缘显脏。
 * ⚠️ "微弱"是关键词：浓度别超过 0.25，再高就像发光体、不像食物。
 * ⚠️ 两层：近距稍浓贴轮廓（多方向叠加出一圈细亮边），远距稀薄铺氛围。
 * ⚠️ 点餐页卡片**不要开**：卡片是白底，白光轮廓完全不可见还浪费性能。
 */
export const FOOD_RIM =
  'drop-shadow(0 0 4px rgba(255,255,255,0.22)) drop-shadow(0 0 12px rgba(255,255,255,0.10))';

