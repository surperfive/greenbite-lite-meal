/**
 * 选择卡·选中：白底 + 青柠描边环（不是 border，是 ring）。
 *
 * ⚠️ 必须带 `ring-inset`：ring 默认画在**边框盒外面**，选中卡的视觉外轮廓会比
 *    同排未选中卡各宽 2px（三列布局里第 3 张会顶出容器右内边距），
 *    肉眼看就是"这张卡没对齐、还大了一圈"。改成 inset 后描边落在边框盒内侧，
 *    三张卡的 border-box 完全一致（实测 21/150.33/279.66，宽 119.33），
 *    1px 透明边框区域是白底，与卡片同色，看不出缝隙。
 */
export const OPTION_CARD_SELECTED =
  'bg-white border-transparent ring-2 ring-inset ring-[#C7F665] shadow-xs';

/**
 * 选择卡·未选中：**白底** + 浅灰描边（2026-10-25 用户：「没选中的是白色底」）。
 *
 * ⚠️ 原来未选中是浅灰 `#f7f9fb`，选中是白底 —— 于是"选中"同时表达了两件事：
 *    底色由灰变白 + 加青柠环。用户要的是一张干净的卡面，灰底反而像"禁用的输入框"，
 *    在详情页那张白面板上显得脏。现在**两种状态都是白底，只靠青柠环 + 勾选徽章 +
 *    标签配色**区分选中，语义反而更清楚（单选组本来就该这样）。
 *
 * ⚠️ 底色变白后，卡面轮廓全靠 `border` —— 所以描边从 `slate-200/90` 提到**实心**
 *    `slate-200`（≈#E2E8F0，白底上 1.35:1，是"看得见但不抢"的 hairline）。
 *    别再把它调回 90% 透明，白底 + 半透明描边会一起糊掉。
 *
 * ⚠️ 原来有 `hover:bg-white`，底色已经是白 → 它是空操作，换成 `hover:border-slate-300`，
 *    hover 时才真有一点反馈。
 */
export const OPTION_CARD_UNSELECTED =
  'bg-white border-slate-200 hover:border-slate-300 shadow-2xs';

