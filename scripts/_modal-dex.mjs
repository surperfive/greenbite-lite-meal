import { chromium } from 'playwright';
import { BASE } from './_base.mjs';
const browser = await chromium.launch({ channel: 'chrome' });
const page = await browser.newPage({ viewport: { width: 430, height: 932 }, deviceScaleFactor: 1 });
await page.goto(BASE, { waitUntil: 'commit' });
await page.waitForSelector('.brand-loader', { state: 'detached', timeout: 20000 }).catch(() => {});
await page.waitForSelector('[data-dish-thumb="true"]', { timeout: 20000 });
await page.click('#nav-tab-gacha');
await page.waitForTimeout(1500);
await page.click('#btn-header-info');
await page.waitForSelector('[role="dialog"]', { timeout: 4000 });
await page.waitForTimeout(800);
await page.screenshot({ path: 'scripts/_shots/_modal-dex.png' });
const m = await page.evaluate(() => {
  const d = document.querySelector('[role="dialog"]');
  const body = d.querySelector('.gb-modal-scroll');
  const owned = body.querySelectorAll('.bg-\\[\\#ECFDC0\\]\\/70').length;
  const rows = body.children.length;
  return { w: d.getBoundingClientRect().width, h: d.getBoundingClientRect().height, rows, owned };
});
console.log(JSON.stringify(m));
await browser.close();
