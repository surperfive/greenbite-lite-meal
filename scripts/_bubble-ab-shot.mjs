import { chromium } from 'playwright';
import path from 'node:path';
const file = 'file:///' + path.resolve('scripts/_bubble-ab.html').replace(/\\/g, '/');
const b = await chromium.launch({ channel: 'chrome' });
const p = await b.newPage({ viewport: { width: 860, height: 1320 }, deviceScaleFactor: 2 });
await p.goto(file, { waitUntil: 'load' });
await p.waitForTimeout(400);
await p.screenshot({ path: 'scripts/_shots/bubble-ab.png', fullPage: true });
console.log('ok', await p.evaluate(() => document.body.scrollHeight));
await b.close();
